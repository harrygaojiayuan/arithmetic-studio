import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { solveTwentyFour } from '../dist/core.mjs';

const entries = [];
for (let a=1;a<=10;a++) for (let b=a;b<=10;b++) for (let c=b;c<=10;c++) for (let d=c;d<=10;d++) {
  const numbers = [a,b,c,d], solution = solveTwentyFour(numbers);
  if (solution) entries.push([...numbers,solution]);
}
const source = '// Generated by scripts/make-twentyfour-bank.mjs. Do not edit by hand.\nexport const TWENTY_FOUR_BANK = Object.freeze([\n'
  + entries.map(entry => `  Object.freeze(${JSON.stringify(entry)}),`).join('\n') + '\n]);\n';
const destination = fileURLToPath(new URL('../dist/twentyfour-bank.mjs', import.meta.url));
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination,'utf8').replace(/\r\n/g,'\n') !== source) throw new Error('24-point bank is out of date; run npm run generate:24');
} else fs.writeFileSync(destination,source);
console.log(`${entries.length} verified hands, ${Buffer.byteLength(source)} bytes`);
